CREATE TABLE effects (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar NOT NULL UNIQUE,
    description varchar NOT NULL,
    CONSTRAINT effects_code_check CHECK (code ~ '^[A-Z][A-Z0-9_]*$'),
    CONSTRAINT effects_description_check CHECK (length(trim(description)) > 0)
);

-- Both creatures and equipment are cards; each occurrence has its own parameters.
CREATE TABLE card_effects (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id integer NOT NULL REFERENCES cards (id) ON DELETE CASCADE,
    effect_id integer NOT NULL REFERENCES effects (id),
    parameters jsonb NOT NULL DEFAULT '{}'::jsonb,
    execution_order integer NOT NULL,
    CONSTRAINT card_effects_parameters_check CHECK (jsonb_typeof(parameters) = 'object'),
    CONSTRAINT card_effects_execution_order_check CHECK (execution_order > 0),
    CONSTRAINT card_effects_card_order_key UNIQUE (card_id, execution_order)
);

CREATE INDEX card_effects_effect_id_idx ON card_effects (effect_id);
