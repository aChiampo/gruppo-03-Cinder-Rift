-- Serialize distribution edits on their parent and freeze configurations referenced by packs.
CREATE FUNCTION protect_referenced_slot_pull_type() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    old_type integer;
    new_type integer;
BEGIN
    IF TG_OP <> 'INSERT' THEN old_type := OLD.id_slot_pull_type; END IF;
    IF TG_OP <> 'DELETE' THEN new_type := NEW.id_slot_pull_type; END IF;
    PERFORM id FROM slot_pull_type WHERE id IN (old_type, new_type) ORDER BY id FOR UPDATE;
    IF EXISTS (SELECT 1 FROM pack_slots WHERE id_slot_pull_type IN (old_type, new_type)) THEN
        RAISE EXCEPTION 'Referenced slot pull types are immutable; create a new configuration'
            USING ERRCODE = '23514', CONSTRAINT = 'slot_pull_type_referenced_check';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER type_pull_rate_protect_references
    BEFORE INSERT OR UPDATE OR DELETE ON type_pull_rate
    FOR EACH ROW EXECUTE FUNCTION protect_referenced_slot_pull_type();

-- Cross-row totals are checked at commit so a profile can be assembled in one transaction.
CREATE FUNCTION check_slot_pull_type_total() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    type_ids integer[];
    type_id integer;
BEGIN
    IF TG_TABLE_NAME = 'slot_pull_type' THEN
        type_ids := ARRAY[NEW.id];
    ELSIF TG_OP = 'INSERT' THEN
        type_ids := ARRAY[NEW.id_slot_pull_type];
    ELSIF TG_OP = 'DELETE' THEN
        type_ids := ARRAY[OLD.id_slot_pull_type];
    ELSE
        type_ids := ARRAY[OLD.id_slot_pull_type, NEW.id_slot_pull_type];
    END IF;
    FOREACH type_id IN ARRAY type_ids LOOP
        IF EXISTS (SELECT 1 FROM slot_pull_type WHERE id = type_id)
            AND (SELECT COALESCE(sum(probability), 0) FROM type_pull_rate
                WHERE id_slot_pull_type = type_id) <> 100.0000 THEN
            RAISE EXCEPTION 'Slot pull type % must total 100.0000 percent', type_id
                USING ERRCODE = '23514', CONSTRAINT = 'slot_pull_type_total_check';
        END IF;
    END LOOP;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER slot_pull_type_total
    AFTER INSERT ON slot_pull_type DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION check_slot_pull_type_total();
CREATE CONSTRAINT TRIGGER type_pull_rate_total
    AFTER INSERT OR UPDATE OR DELETE ON type_pull_rate DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION check_slot_pull_type_total();

