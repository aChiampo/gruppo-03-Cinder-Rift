CREATE TABLE roles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar NOT NULL UNIQUE
);

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname varchar NOT NULL UNIQUE,
    hash_password varchar NOT NULL,
    email varchar NOT NULL UNIQUE,
    ranking_points integer NOT NULL DEFAULT 1000,
    registration_date timestamptz NOT NULL DEFAULT now(),
    url_user_icon varchar,
    id_role integer NOT NULL CONSTRAINT users_id_role_fk REFERENCES roles (id),
    is_deleted boolean NOT NULL DEFAULT false
);

CREATE TABLE inventory (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user integer NOT NULL UNIQUE CONSTRAINT inventory_id_user_fk REFERENCES users (id),
    cobalt_shards integer NOT NULL DEFAULT 0,
    rift_cores integer NOT NULL DEFAULT 0,
    scraps integer NOT NULL DEFAULT 0
);

CREATE TABLE refresh_tokens (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user integer NOT NULL CONSTRAINT refresh_tokens_id_user_fk REFERENCES users (id),
    token_hash varchar NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    revoked_at timestamptz
);

CREATE TABLE password_reset_tokens (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user integer NOT NULL CONSTRAINT password_reset_tokens_id_user_fk REFERENCES users (id),
    token_hash varchar NOT NULL UNIQUE,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    used_at timestamptz
);
