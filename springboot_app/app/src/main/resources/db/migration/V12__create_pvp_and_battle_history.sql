CREATE TABLE battle_history (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode varchar NOT NULL,
    player_a_id integer NOT NULL CONSTRAINT battle_history_player_a_id_fk REFERENCES users (id) ON DELETE CASCADE,
    player_b_id integer CONSTRAINT battle_history_player_b_id_fk REFERENCES users (id) ON DELETE SET NULL,
    winner_id integer CONSTRAINT battle_history_winner_id_fk REFERENCES users (id) ON DELETE SET NULL,
    outcome varchar NOT NULL,
    deck_a_snapshot jsonb NOT NULL,
    deck_b_snapshot jsonb,
    battle_log jsonb NOT NULL DEFAULT '[]'::jsonb,
    ranking_delta integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX battle_history_player_a_created_idx
    ON battle_history (player_a_id, created_at DESC);

CREATE INDEX battle_history_player_b_created_idx
    ON battle_history (player_b_id, created_at DESC);

CREATE TABLE pvp_matchmaking_queue (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL CONSTRAINT pvp_matchmaking_queue_user_id_fk REFERENCES users (id) ON DELETE CASCADE,
    deck_id integer NOT NULL CONSTRAINT pvp_matchmaking_queue_deck_id_fk REFERENCES decks (id) ON DELETE CASCADE,
    deck_snapshot jsonb NOT NULL,
    status varchar NOT NULL,
    battle_history_id integer CONSTRAINT pvp_matchmaking_queue_battle_history_id_fk REFERENCES battle_history (id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pvp_matchmaking_queue_status_check CHECK (status IN ('WAITING', 'MATCHING', 'MATCHED', 'CANCELLED'))
);

CREATE UNIQUE INDEX pvp_matchmaking_queue_active_user_uk
    ON pvp_matchmaking_queue (user_id)
    WHERE status IN ('WAITING', 'MATCHING');

CREATE TABLE pvp_challenges (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenger_id integer NOT NULL CONSTRAINT pvp_challenges_challenger_id_fk REFERENCES users (id) ON DELETE CASCADE,
    opponent_id integer NOT NULL CONSTRAINT pvp_challenges_opponent_id_fk REFERENCES users (id) ON DELETE CASCADE,
    challenger_deck_id integer NOT NULL CONSTRAINT pvp_challenges_challenger_deck_id_fk REFERENCES decks (id) ON DELETE CASCADE,
    challenger_deck_snapshot jsonb NOT NULL,
    opponent_deck_id integer CONSTRAINT pvp_challenges_opponent_deck_id_fk REFERENCES decks (id) ON DELETE SET NULL,
    status varchar NOT NULL,
    battle_history_id integer CONSTRAINT pvp_challenges_battle_history_id_fk REFERENCES battle_history (id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    responded_at timestamptz,
    CONSTRAINT pvp_challenges_distinct_players_check CHECK (challenger_id <> opponent_id),
    CONSTRAINT pvp_challenges_status_check CHECK (status IN ('PENDING', 'COMPLETED', 'DECLINED', 'CANCELLED'))
);

CREATE INDEX pvp_challenges_opponent_status_idx
    ON pvp_challenges (opponent_id, status, created_at DESC);

CREATE INDEX pvp_challenges_challenger_status_idx
    ON pvp_challenges (challenger_id, status, created_at DESC);
