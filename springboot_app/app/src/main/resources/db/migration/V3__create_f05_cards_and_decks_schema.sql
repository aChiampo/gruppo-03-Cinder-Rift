CREATE TABLE card_types (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar UNIQUE,
    is_deleted boolean NOT NULL DEFAULT false,
    code varchar NOT NULL UNIQUE
);

CREATE TABLE rarities (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar UNIQUE,
    name varchar UNIQUE,
    order_index integer,
    is_deleted boolean NOT NULL DEFAULT false
);

CREATE TABLE factions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar UNIQUE,
    name varchar UNIQUE,
    url_faction_icon varchar,
    is_deleted boolean NOT NULL DEFAULT false
);

CREATE TABLE expansions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar UNIQUE,
    name varchar UNIQUE,
    released_at date,
    is_active boolean,
    url_expansion_icon varchar,
    is_deleted boolean NOT NULL DEFAULT false
);

CREATE TABLE cards (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar,
    description varchar,
    id_type integer CONSTRAINT cards_id_type_fk REFERENCES card_types (id),
    energy_cost integer,
    power integer,
    id_rarity integer CONSTRAINT cards_id_rarity_fk REFERENCES rarities (id),
    value_atk integer,
    value_def integer,
    id_faction integer CONSTRAINT cards_id_faction_fk REFERENCES factions (id),
    id_expansion integer CONSTRAINT cards_id_expansion_fk REFERENCES expansions (id),
    is_deleted boolean NOT NULL DEFAULT false
);

CREATE TABLE cards_arts (
    id_card integer NOT NULL,
    art_code varchar NOT NULL,
    id_art integer GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
    url_card_art varchar UNIQUE,
    CONSTRAINT cards_arts_pkey PRIMARY KEY (id_card, art_code),
    CONSTRAINT cards_arts_id_card_fk FOREIGN KEY (id_card) REFERENCES cards (id),
    CONSTRAINT cards_arts_card_art_key UNIQUE (id_card, id_art)
);

CREATE TABLE collections (
    id_user integer NOT NULL,
    id_card integer NOT NULL,
    id_card_art integer NOT NULL,
    owned_replica integer NOT NULL,
    tradable_replica integer NOT NULL,
    CONSTRAINT collections_pkey PRIMARY KEY (id_user, id_card, id_card_art),
    CONSTRAINT collections_id_user_fk FOREIGN KEY (id_user) REFERENCES users (id),
    CONSTRAINT collections_id_card_fk FOREIGN KEY (id_card) REFERENCES cards (id),
    CONSTRAINT collections_card_art_fk FOREIGN KEY (id_card, id_card_art)
        REFERENCES cards_arts (id_card, id_art),
    CONSTRAINT collections_owned_replica_check CHECK (owned_replica > 0),
    CONSTRAINT collections_tradable_replica_check
        CHECK (tradable_replica >= 0 AND tradable_replica <= owned_replica)
);

CREATE TABLE round_configurations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_name varchar NOT NULL UNIQUE,
    round_number integer NOT NULL,
    max_energy integer NOT NULL,
    max_cards integer NOT NULL,
    CONSTRAINT round_configurations_round_number_check CHECK (round_number > 0),
    CONSTRAINT round_configurations_max_energy_check CHECK (max_energy > 0),
    CONSTRAINT round_configurations_max_cards_check CHECK (max_cards > 0)
);

CREATE TABLE decks (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user integer NOT NULL CONSTRAINT decks_id_user_fk REFERENCES users (id),
    is_challengeable boolean NOT NULL DEFAULT false
);

CREATE TABLE decks_cards (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_deck integer NOT NULL,
    id_card integer NOT NULL,
    id_card_art integer NOT NULL,
    destination varchar NOT NULL,
    CONSTRAINT decks_cards_id_deck_fk FOREIGN KEY (id_deck)
        REFERENCES decks (id) ON DELETE CASCADE,
    CONSTRAINT decks_cards_id_card_fk FOREIGN KEY (id_card) REFERENCES cards (id),
    CONSTRAINT decks_cards_card_art_fk FOREIGN KEY (id_card, id_card_art)
        REFERENCES cards_arts (id_card, id_art),
    CONSTRAINT decks_cards_destination_fk FOREIGN KEY (destination)
        REFERENCES round_configurations (round_name)
);
