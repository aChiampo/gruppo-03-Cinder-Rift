-- Configuration and ownership only. Commercial package data will be added separately.
CREATE TABLE artwork_pull_rates (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    standard numeric(5,2) NOT NULL DEFAULT 81.00,
    extended_art numeric(5,2) NOT NULL DEFAULT 10.00,
    full_art numeric(5,2) NOT NULL DEFAULT 7.50,
    alternate_art numeric(5,2) NOT NULL DEFAULT 1.50,
    CONSTRAINT artwork_pull_rates_range_check CHECK (
        standard BETWEEN 0 AND 100 AND extended_art BETWEEN 0 AND 100
        AND full_art BETWEEN 0 AND 100 AND alternate_art BETWEEN 0 AND 100),
    CONSTRAINT artwork_pull_rates_total_check
        CHECK (standard + extended_art + full_art + alternate_art = 100)
);

