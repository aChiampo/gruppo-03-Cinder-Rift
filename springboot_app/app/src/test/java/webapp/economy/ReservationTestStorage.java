package webapp.economy;

import java.time.OffsetDateTime;
import org.springframework.jdbc.core.simple.JdbcClient;

/** Test-only F06 storage. Deliberately not a Flyway migration or application startup script. */
public final class ReservationTestStorage {
    private ReservationTestStorage() { }

    public static void install(JdbcClient jdbc) {
        jdbc.sql("""
                CREATE TABLE original_announces (
                    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    publisher_id integer NOT NULL REFERENCES users(id),
                    created_at timestamptz NOT NULL DEFAULT now(), expires_at timestamptz NOT NULL,
                    status varchar NOT NULL, is_private boolean NOT NULL, is_negotiable boolean NOT NULL,
                    original_p_cards_offer jsonb NOT NULL DEFAULT '[]', original_p_token_offer bigint NOT NULL DEFAULT 0,
                    original_r_cards_offer jsonb NOT NULL DEFAULT '[]', original_r_token_offer bigint NOT NULL DEFAULT 0)
                """).update();
        jdbc.sql("""
                CREATE TABLE current_negotiations (
                    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    announce_id integer NOT NULL UNIQUE REFERENCES original_announces(id),
                    publisher_id integer NOT NULL REFERENCES users(id), responder_id integer NOT NULL REFERENCES users(id),
                    is_private boolean NOT NULL, is_negotiable boolean NOT NULL,
                    current_p_cards_offer jsonb NOT NULL DEFAULT '[]', current_p_token_offer bigint NOT NULL DEFAULT 0,
                    current_r_cards_offer jsonb NOT NULL DEFAULT '[]', current_r_token_offer bigint NOT NULL DEFAULT 0,
                    offer_version bigint NOT NULL DEFAULT 1,
                    p_acceptance boolean NOT NULL DEFAULT false, r_acceptance boolean NOT NULL DEFAULT false)
                """).update();
        jdbc.sql("""
                CREATE TABLE trade_token_reservations (
                    negotiation_id integer NOT NULL REFERENCES current_negotiations(id) ON DELETE CASCADE,
                    id_user integer NOT NULL REFERENCES inventory(id_user), offer_version bigint NOT NULL,
                    token_amount bigint NOT NULL, created_at timestamptz NOT NULL DEFAULT now(), expires_at timestamptz NOT NULL,
                    PRIMARY KEY (negotiation_id, id_user))
                """).update();
    }

    public static int hold(JdbcClient jdbc, int owner, int other, long amount, OffsetDateTime expires) {
        int announce = jdbc.sql("""
                INSERT INTO original_announces (publisher_id, expires_at, status, is_private, is_negotiable, original_p_token_offer)
                VALUES (:owner, :expires, 'PENDING', false, true, :amount) RETURNING id
                """).param("owner", owner).param("expires", expires).param("amount", amount).query(Integer.class).single();
        int negotiation = jdbc.sql("""
                INSERT INTO current_negotiations
                    (announce_id, publisher_id, responder_id, is_private, is_negotiable, current_p_token_offer, p_acceptance)
                VALUES (:announce, :owner, :other, false, true, :amount, true) RETURNING id
                """).param("announce", announce).param("owner", owner).param("other", other).param("amount", amount)
                .query(Integer.class).single();
        jdbc.sql("INSERT INTO trade_token_reservations (negotiation_id, id_user, offer_version, token_amount, expires_at) VALUES (:id, :owner, 1, :amount, :expires)")
                .param("id", negotiation).param("owner", owner).param("amount", amount).param("expires", expires).update();
        return negotiation;
    }

    public static void remove(JdbcClient jdbc) {
        jdbc.sql("DROP TABLE IF EXISTS trade_token_reservations").update();
        jdbc.sql("DROP TABLE IF EXISTS current_negotiations").update();
        jdbc.sql("DROP TABLE IF EXISTS original_announces").update();
    }
}
