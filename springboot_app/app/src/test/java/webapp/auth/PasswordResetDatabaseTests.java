/** Real PostgreSQL commits, locks and rollbacks in an isolated, disposable schema. */
@SpringBootTest(classes = AppApplication.class, properties = {"app.security.session-token-cleanup-cron=-",
        "app.security.password-reset-token-cleanup-cron=-"})
class PasswordResetDatabaseTests {
    private static final Instant NOW = Instant.parse("2026-11-12T12:00:00Z");
    @Autowired private DataSource dataSource;
    @Autowired private JwtEncoder jwtEncoder;
    private String schema;
    private JdbcClient jdbc;
    private AccountRepository accounts;
    private PasswordEncoder passwords;
    private MutableClock clock;
    private AnnotationConfigApplicationContext transactions;
    private AuthenticationService authentication;

    @BeforeEach
    void setUp() throws Exception {
        schema = "password_reset_test_" + UUID.randomUUID().toString().replace("-", "");
        try (var connection = dataSource.getConnection(); var statement = connection.createStatement()) {
            statement.execute("CREATE SCHEMA " + schema);
        }
        DataSource isolated = new DelegatingDataSource(dataSource) {
            @Override
            public java.sql.Connection getConnection() throws java.sql.SQLException {
                var connection = super.getConnection();
                connection.setSchema(schema);
                return (java.sql.Connection) Proxy.newProxyInstance(
                        connection.getClass().getClassLoader(),
                        new Class<?>[] {java.sql.Connection.class},
                        (proxy, method, args) -> {
                            if (method.getName().equals("close")) {
                                try {
                                    connection.setSchema("public");
                                } finally {
                                    connection.close();
                                }
                                return null;
                            }
                            try {
                                return method.invoke(connection, args);
                            } catch (InvocationTargetException exception) {
                                throw exception.getCause();
                            }
                        });
            }
        };
        jdbc = JdbcClient.create(isolated);
        jdbc.sql("CREATE TABLE roles (id int PRIMARY KEY, code varchar NOT NULL UNIQUE)").update();
        jdbc.sql("""
                CREATE TABLE users (id int PRIMARY KEY, nickname varchar NOT NULL, email varchar NOT NULL UNIQUE,
                    hash_password varchar NOT NULL, id_role int NOT NULL REFERENCES roles(id),
                    is_deleted boolean NOT NULL DEFAULT false, ranking_points int NOT NULL DEFAULT 1000,
                    url_user_icon varchar)
                """).update();
        jdbc.sql("""
                CREATE TABLE password_reset_tokens (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_user int NOT NULL REFERENCES users(id), token_hash varchar NOT NULL UNIQUE,
                    expires_at timestamptz NOT NULL, created_at timestamptz NOT NULL DEFAULT now(), used_at timestamptz)
                """).update();
        jdbc.sql("""
                CREATE TABLE refresh_tokens (id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    id_user int NOT NULL REFERENCES users(id), token_hash varchar NOT NULL UNIQUE,
                    expires_at timestamptz NOT NULL, created_at timestamptz NOT NULL DEFAULT now(), revoked_at timestamptz)
                """).update();
        jdbc.sql("INSERT INTO roles VALUES (1, 'USER'), (2, 'ADMIN'), (3, 'OTHER')").update();
        passwords = spy(new BCryptPasswordEncoder(4));
        jdbc.sql("""
                INSERT INTO users (id, nickname, email, hash_password, id_role) VALUES
                    (1, 'Player', 'player@example.invalid', :hash, 1),
                    (2, 'Other', 'other@example.invalid', :hash, 2)
                """).param("hash", passwords.encode("old password")).update();
        clock = new MutableClock();
        accounts = new AccountRepository(jdbc);
        transactions = new AnnotationConfigApplicationContext();
        transactions.register(TransactionConfig.class);
        transactions.registerBean("transactionManager", DataSourceTransactionManager.class,
                () -> new DataSourceTransactionManager(isolated));
        transactions.registerBean(AuthenticationService.class, () -> new AuthenticationService(
                accounts, passwords, jwtEncoder, clock, Duration.ofMinutes(15), Duration.ofDays(14)));
        transactions.refresh();
        authentication = transactions.getBean(AuthenticationService.class);
    }

    @AfterEach
    void tearDown() throws Exception {
        if (transactions != null) {
            transactions.close();
        }
        // Only the generated schema owned by this test is removed; existing application data is untouched.
        if (schema != null && schema.matches("password_reset_test_[a-f0-9]{32}")) {
            try (var connection = dataSource.getConnection(); var statement = connection.createStatement()) {
                statement.execute("DROP SCHEMA " + schema + " CASCADE");
            }
        }
    }

    @Test
    void repeatedRequestsPreserveEarlierTokensAndExpireExactlyAfterTenMinutes() {
        authentication.requestPasswordReset(" PLAYER@EXAMPLE.INVALID ");
        clock.now = NOW.plusSeconds(30);
        authentication.requestPasswordReset("player@example.invalid");
        assertThat(jdbc.sql("SELECT token_hash FROM password_reset_tokens").query(String.class).list())
                .hasSize(2).doesNotHaveDuplicates().allMatch(hash -> hash.matches("[a-f0-9]{64}"));
        assertThat(jdbc.sql("SELECT extract(epoch FROM expires_at - created_at)::int FROM password_reset_tokens")
                .query(Integer.class).list()).containsExactly(600, 600);
        assertThat(jdbc.sql("SELECT count(*) FROM password_reset_tokens WHERE used_at IS NULL")
                .query(Integer.class).single()).isEqualTo(2);
        assertThat(jdbc.sql("SELECT hash_password FROM users WHERE id = 1").query(String.class).single())
                .satisfies(hash -> assertThat(passwords.matches("old password", hash)).isTrue());
    }

    @Test
    void unknownDeletedAndUnsupportedRoleAccountsDoNotReceiveTokens() {
        jdbc.sql("UPDATE users SET is_deleted = true WHERE id = 1").update();
        jdbc.sql("UPDATE users SET id_role = 3 WHERE id = 2").update();
        authentication.requestPasswordReset("unknown@example.invalid");
        authentication.requestPasswordReset("player@example.invalid");
        authentication.requestPasswordReset("other@example.invalid");
        assertThat(jdbc.sql("SELECT count(*) FROM password_reset_tokens").query(Integer.class).single()).isZero();
    }

    @Test
    void successfulResetConsumesLinkDeletesOtherLinksAndRevokesOnlyOwnersSessions() throws Exception {
        String token = seedToken(1, NOW.plusSeconds(600));
        seedToken(1, NOW.plusSeconds(600));
        String otherToken = seedToken(2, NOW.plusSeconds(600));
        var firstSession = authentication.login("player@example.invalid", "old password");
        var secondSession = authentication.login("player@example.invalid", "old password");
        var otherSession = authentication.login("other@example.invalid", "old password");
        authentication.resetPassword(token, "  new password  ");
        assertThat(accounts.findActiveSessionProfile(1, sessionId(firstSession), NOW)).isEmpty();
        assertThat(accounts.findActiveSessionProfile(1, sessionId(secondSession), NOW)).isEmpty();
        assertThat(accounts.findActiveSessionProfile(2, sessionId(otherSession), NOW)).isPresent();
        assertThat(jdbc.sql("SELECT count(*) FROM password_reset_tokens WHERE id_user = 1 AND used_at IS NULL")
                .query(Integer.class).single()).isZero();
        assertThat(jdbc.sql("SELECT used_at IS NOT NULL FROM password_reset_tokens WHERE token_hash = :hash")
                .param("hash", hash(token)).query(Boolean.class).single()).isTrue();
        assertThat(accounts.findPasswordResetTokenOwner(hash(otherToken))).contains(2);
        assertInvalid(token);
        assertThatThrownBy(() -> authentication.login("player@example.invalid", "old password"))
                .isInstanceOf(ResponseStatusException.class);
        assertThat(authentication.login("player@example.invalid", "  new password  ").user().id()).isEqualTo(1);
    }

    @Test
    void malformedUnknownExpiredUsedAndInactiveTokensAreRejectedWithoutPasswordChanges() throws Exception {
        assertInvalid("bad");
        assertInvalid(randomToken());
        assertInvalid(seedToken(1, NOW));
        assertInvalid(seedToken(1, NOW.minusSeconds(1)));
        String used = seedToken(1, NOW.plusSeconds(600));
        jdbc.sql("UPDATE password_reset_tokens SET used_at = :now WHERE token_hash = :hash")
                .param("now", NOW.atOffset(ZoneOffset.UTC)).param("hash", hash(used)).update();
        assertInvalid(used);
        String deleted = seedToken(1, NOW.plusSeconds(600));
        jdbc.sql("UPDATE users SET is_deleted = true WHERE id = 1").update();
        assertInvalid(deleted);
        String unsupported = seedToken(2, NOW.plusSeconds(600));
        jdbc.sql("UPDATE users SET id_role = 3 WHERE id = 2").update();
        assertInvalid(unsupported);
        assertThat(jdbc.sql("SELECT hash_password FROM users WHERE id = 1").query(String.class).single())
                .satisfies(value -> assertThat(passwords.matches("old password", value)).isTrue());
    }

    @Test
    void passwordByteLimitPreservesTokenOnRejection() throws Exception {
        String token = seedToken(1, NOW.plusSeconds(600));
        assertThatThrownBy(() -> authentication.resetPassword(token, "é".repeat(37)))
                .isInstanceOf(ResponseStatusException.class);
        authentication.resetPassword(token, "é".repeat(36));
        assertThat(authentication.login("player@example.invalid", "é".repeat(36))).isNotNull();
    }

    @Test
    void failureAfterPasswordAndTokenWritesRollsBackTheWholeReset() throws Exception {
        String token = seedToken(1, NOW.plusSeconds(600));
        seedToken(1, NOW.plusSeconds(600));
        var session = authentication.login("player@example.invalid", "old password");
        // Force the last write to fail after the password update and deletion of other recovery links.
        jdbc.sql("ALTER TABLE refresh_tokens ADD CONSTRAINT reject_revocation CHECK (revoked_at IS NULL)").update();
        assertThatThrownBy(() -> authentication.resetPassword(token, "new password"))
                .isInstanceOf(org.springframework.dao.DataIntegrityViolationException.class);
        assertThat(jdbc.sql("SELECT count(*) FROM password_reset_tokens WHERE used_at IS NULL")
                .query(Integer.class).single()).isEqualTo(2);
        assertThat(accounts.findActiveSessionProfile(1, sessionId(session), NOW)).isPresent();
        assertThat(authentication.login("player@example.invalid", "old password")).isNotNull();
    }

    @ParameterizedTest
    @ValueSource(booleans = {true, false})
    void concurrentResetsHaveOnlyOneWinner(boolean sameToken) throws Exception {
        String first = seedToken(1, NOW.plusSeconds(600));
        String second = sameToken ? first : seedToken(1, NOW.plusSeconds(600));
        var ready = new CountDownLatch(2);
        var start = new CountDownLatch(1);
        try (var executor = Executors.newVirtualThreadPerTaskExecutor()) {
            var a = executor.submit(() -> resetConcurrently(first, ready, start));
            var b = executor.submit(() -> resetConcurrently(second, ready, start));
            assertThat(ready.await(10, TimeUnit.SECONDS)).isTrue();
            start.countDown();
            assertThat(java.util.List.of(a.get(10, TimeUnit.SECONDS), b.get(10, TimeUnit.SECONDS)))
                    .containsExactlyInAnyOrder(true, false);
        }
    }

    @Test
    void loginWaitingBehindResetChecksTheNewPasswordAndRefreshCannotSurvive() throws Exception {
        String token = seedToken(1, NOW.plusSeconds(600));
        var session = authentication.login("player@example.invalid", "old password");
        var hashing = new CountDownLatch(1);
        var finish = new CountDownLatch(1);
        doAnswer(invocation -> {
            if ("new password".contentEquals(invocation.getArgument(0, CharSequence.class))) {
                hashing.countDown();
                if (!finish.await(10, TimeUnit.SECONDS)) {
                    throw new IllegalStateException("Timed out waiting for reset test");
                }
            }
            return invocation.callRealMethod();
        }).when(passwords).encode(anyString());
        try (var executor = Executors.newVirtualThreadPerTaskExecutor()) {
            var reset = executor.submit(() -> authentication.resetPassword(token, "new password"));
            try {
                assertThat(hashing.await(10, TimeUnit.SECONDS)).isTrue();
                var loginStarted = new CountDownLatch(1);
                var login = executor.submit(() -> {
                    loginStarted.countDown();
                    assertThatThrownBy(() -> authentication.login("player@example.invalid", "old password"))
                            .isInstanceOf(ResponseStatusException.class);
                });
                var renewal = executor.submit(() -> assertThatThrownBy(() -> authentication.renew(session.refreshToken()))
                        .isInstanceOf(ResponseStatusException.class));
                assertThat(loginStarted.await(10, TimeUnit.SECONDS)).isTrue();
                finish.countDown();
                reset.get(10, TimeUnit.SECONDS);
                login.get(10, TimeUnit.SECONDS);
                renewal.get(10, TimeUnit.SECONDS);
            } finally {
                finish.countDown();
            }
        }
        assertThat(accounts.findActiveSessionProfile(1, sessionId(session), NOW)).isEmpty();
    }

    @Test
    void cleanupDeletesUsedAndExpiredTokensButPreservesUsableOnes() throws Exception {
        seedToken(1, NOW);
        seedToken(1, NOW.minusSeconds(1));
        String usable = seedToken(1, NOW.plusSeconds(1));
        String used = seedToken(2, NOW.plusSeconds(600));
        jdbc.sql("UPDATE password_reset_tokens SET used_at = :now WHERE token_hash = :hash")
                .param("now", NOW.atOffset(ZoneOffset.UTC)).param("hash", hash(used)).update();
        new PasswordResetTokenCleanup(accounts, clock).cleanUp();
        assertThat(jdbc.sql("SELECT token_hash FROM password_reset_tokens").query(String.class).list())
                .containsExactly(hash(usable));
        assertThat(accounts.deleteExpiredOrUsedPasswordResetTokens(NOW)).isZero();
    }

    private boolean resetConcurrently(String token, CountDownLatch ready, CountDownLatch start) throws Exception {
        ready.countDown();
        if (!start.await(10, TimeUnit.SECONDS)) {
            throw new IllegalStateException("Timed out waiting for reset test");
        }
        try {
            authentication.resetPassword(token, "new password");
            return true;
        } catch (ResponseStatusException exception) {
            assertThat(exception.getStatusCode().value()).isEqualTo(400);
            return false;
        }
    }

    private String seedToken(int userId, Instant expiry) throws Exception {
        String token = randomToken();
        accounts.insertPasswordResetToken(userId, hash(token), NOW, expiry);
        return token;
    }

    private static String randomToken() {
        byte[] bytes = new byte[32];
        new java.security.SecureRandom().nextBytes(bytes);
        return Base64.getUrlEncoder().withoutPadding().encodeToString(bytes);
    }

    private static String hash(String token) throws Exception {
        return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256")
                .digest(token.getBytes(StandardCharsets.US_ASCII)));
    }

    private static int sessionId(AuthenticationService.IssuedSession session) {
        String payload = new String(Base64.getUrlDecoder().decode(session.accessToken().split("\\.")[1]),
                StandardCharsets.UTF_8);
        return Integer.parseInt(com.jayway.jsonpath.JsonPath.read(payload, "$.sid"));
    }

    private void assertInvalid(String token) {
        assertThatThrownBy(() -> authentication.resetPassword(token, "new password"))
                .isInstanceOfSatisfying(ResponseStatusException.class, exception -> {
                    assertThat(exception.getStatusCode().value()).isEqualTo(400);
                    assertThat(exception.getReason()).isEqualTo("Invalid password reset token");
                });
    }

    @Configuration(proxyBeanMethods = false)
    @EnableTransactionManagement
    static class TransactionConfig {}

    static class MutableClock extends Clock {
        volatile Instant now = NOW;
        @Override public ZoneId getZone() { return ZoneOffset.UTC; }
        @Override public Clock withZone(ZoneId zone) { return Clock.fixed(now, zone); }
        @Override public Instant instant() { return now; }
    }
}
